/*
 * kairos-splash — the kAIrOS boot screen painter [R73/R28/R51]
 *
 * One small static binary, started from the initramfs (scripts/init-top/kairos-splash,
 * before udev loads the GPU driver) and alive until the kiosk is up:
 *
 *   phase 1  the firmware's own logo (ACPI BGRT) redrawn where the firmware put it, with
 *            the "kAIrOS by mAIer" lockup centred under its non-black bounding box
 *            (Kubuntu/Ubuntu style) — on black. No BGRT: the lockup alone, centred.
 *   phase 2  the loading screen (phase 1 fades out to the bare wallpaper, then this fades
 *            in — the two layouts are never on screen together): the thick wordmark on the shell's
 *            wallpaper gradient with a rounded, glowing, accent-gradient loading bar whose
 *            progress is determinate (elapsed vs the expected boot time measured by the
 *            kernel over the last boots) and jumps forward at milestones (root mounted,
 *            userspace, X starting). A soft highlight keeps moving so it never looks dead.
 *
 * Framebuffer rules (kairos-e3, stick logs 2026-10-07): efifb is fb0 at ~0.03 s, amdgpu
 * replaces it at ~1 s. efifb's mmap is a raw PFN mapping that unregistering does NOT
 * revoke — stale writes would land silently in memory amdgpu reclaims. So this painter
 * never mmaps: every frame is pwrite()n, and the kernel's fb_write path answers ENODEV
 * the moment the fb_info behind the open file is unregistered. FBIOGET_VSCREENINFO is
 * still asked before EVERY frame (ENODEV = handover, and the geometry is re-read: the
 * DRM fbdev's mode can differ from the GOP mode). On ENODEV the file is closed and
 * never touched again; /dev/fb0 is reopened as soon as it exists again (<=10 ms poll),
 * and the frame is repainted at once — amdgpudrmfb commits a zeroed buffer first.
 *
 * VT: tty1 is put into KD_GRAPHICS so fbcon cannot paint over the screen. The text
 * console comes back ONLY on failure exits (SIGTERM/SIGINT/SIGHUP, a crash, `--stop`
 * from the initramfs panic hook or the emergency/rescue drop-ins). The normal handover
 * (SIGUSR1, or the kiosk user's flag file /run/kairos/splash-handover — X already runs
 * on VT1 and owns its mode) exits WITHOUT touching the mode. A kernel panic prints only
 * on a text-mode VT: pstore (kairos-bootlog-early copies it) stays the record [R51].
 *
 * Survives switch_root: argv[0] starts with '@' (re-exec), and because initramfs-tools
 * MOVES /dev /sys /run /proc into the new root and run-init empties the old rootfs, the
 * painter keeps directory fds of those four from its start and only ever openat()s
 * through them; the final log archive is reached through /proc/1/root.
 *
 * Logs to /run/kairos-splash.log (every step, uptime-stamped), appended to
 * /var/log/kairos/splash.log at exit (kairos-bootlog quotes both) [R51].
 * Cosmetic: no path here can block or fail the boot — every error is logged and the
 * painter carries on or leaves quietly [R63].
 *
 * Test hooks (no kernel needed): KAIROS_FB=<regular file> renders into that file with
 * the geometry read from KAIROS_FB_SYS/{virtual_size,bits_per_pixel,stride,name}; the
 * file KAIROS_FB_SYS/enodev simulates the unregistered fb (the fake ioctl layer).
 * `--once --at T --phase N` renders one frame; `--layout`/`--bgrt-info` print the maths.
 *
 * Build: scripts/splash/build.sh (cc -O2 -static). Assets: scripts/splash/logo_data.h
 * (generated by scripts/splash/render-assets.py from the shell's font).
 */

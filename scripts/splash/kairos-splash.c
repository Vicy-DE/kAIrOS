/* ---- small helpers ---------------------------------------------------------------- */
static inline uint8_t clamp8(double v) { return v <= 0 ? 0 : v >= 255 ? 255 : (uint8_t)(v + 0.5); }
static inline double clampd(double v, double lo, double hi) { return v < lo ? lo : v > hi ? hi : v; }
static inline void lerp3(uint8_t *out, const uint8_t *a, const uint8_t *b, double t) {
    for (int i = 0; i < 3; i++) out[i] = clamp8(a[i] + (b[i] - a[i]) * t);
}

static int read_file_at(int dfd, const char *path, char *buf, size_t cap) {
    int fd = dfd >= 0 ? openat(dfd, path, O_RDONLY | O_CLOEXEC) : open(path, O_RDONLY | O_CLOEXEC);
    if (fd < 0) return -1;
    ssize_t n = 0, r;
    while ((size_t)n < cap - 1 && (r = read(fd, buf + n, cap - 1 - n)) > 0) n += r;
    close(fd);
    buf[n] = 0;
    return (int)n;
}

static int write_file_at(int dfd, const char *path, const char *text) {
    int fd = dfd >= 0 ? openat(dfd, path, O_WRONLY | O_CREAT | O_TRUNC | O_CLOEXEC, 0644)
                      : open(path, O_WRONLY | O_CREAT | O_TRUNC | O_CLOEXEC, 0644);
    if (fd < 0) return -1;
    ssize_t r = write(fd, text, strlen(text)); (void)r;
    close(fd);
    return 0;
}

/* ---- sprites (RLE from logo_data.h) ------------------------------------------------ */
static Sprite decode_sprite(int w, int h, const unsigned char *rgb, size_t rgb_n, const unsigned char *al, size_t al_n) {
    Sprite s = {w, h, calloc((size_t)w * h, 4)};
    if (!s.rgba) { s.w = s.h = 0; return s; }
    size_t px = 0, i = 0, n = (size_t)w * h;
    while (i + 3 < rgb_n && px < n) {
        unsigned cnt = rgb[i];
        for (unsigned k = 0; k < cnt && px < n; k++, px++) {
            s.rgba[px * 4] = rgb[i + 1]; s.rgba[px * 4 + 1] = rgb[i + 2]; s.rgba[px * 4 + 2] = rgb[i + 3];
        }
        i += 4;
    }
    px = 0; i = 0;
    while (i + 1 < al_n && px < n) {
        unsigned cnt = al[i];
        for (unsigned k = 0; k < cnt && px < n; k++, px++) s.rgba[px * 4 + 3] = al[i + 1];
        i += 2;
    }
    return s;
}

/* bilinear sample of a straight-alpha sprite at (u, v) in sprite pixels */
static inline void sprite_sample(const Sprite *s, double u, double v, double out[4]) {
    u -= 0.5; v -= 0.5;
    int x0 = (int)floor(u), y0 = (int)floor(v);
    double fx = u - x0, fy = v - y0;
    double acc[4] = {0, 0, 0, 0}, wsum = 0;
    for (int j = 0; j < 2; j++) for (int i = 0; i < 2; i++) {
        int x = x0 + i, y = y0 + j;
        double wgt = (i ? fx : 1 - fx) * (j ? fy : 1 - fy);
        if (x < 0 || y < 0 || x >= s->w || y >= s->h || wgt <= 0) continue;
        const uint8_t *p = s->rgba + ((size_t)y * s->w + x) * 4;
        double a = p[3] / 255.0 * wgt;
        acc[0] += p[0] * a; acc[1] += p[1] * a; acc[2] += p[2] * a; acc[3] += a;
        wsum += wgt;
    }
    (void)wsum;
    if (acc[3] > 0) { out[0] = acc[0] / acc[3]; out[1] = acc[1] / acc[3]; out[2] = acc[2] / acc[3]; }
    else out[0] = out[1] = out[2] = 0;
    out[3] = acc[3];   /* coverage 0..1 */
}

/* draw the sprite scaled to dw x dh with its top-left at (dx, dy), alpha-blended; area-averaged when downscaling */
static void blit_sprite(Img *dst, const Sprite *s, int dx, int dy, int dw, int dh, double opacity) {
    if (dw <= 0 || dh <= 0 || !s->rgba) return;
    double sx = (double)s->w / dw, sy = (double)s->h / dh;
    int ss = (sx > 1.0 || sy > 1.0) ? (int)ceil(fmax(sx, sy)) : 1;   /* supersamples per axis when shrinking */
    if (ss > 4) ss = 4;
    for (int y = 0; y < dh; y++) {
        int py = dy + y; if (py < 0 || py >= dst->h) continue;
        for (int x = 0; x < dw; x++) {
            int px = dx + x; if (px < 0 || px >= dst->w) continue;
            double c[4] = {0, 0, 0, 0};
            for (int j = 0; j < ss; j++) for (int i = 0; i < ss; i++) {
                double smp[4];
                sprite_sample(s, (x + (i + 0.5) / ss) * sx, (y + (j + 0.5) / ss) * sy, smp);
                c[0] += smp[0] * smp[3]; c[1] += smp[1] * smp[3]; c[2] += smp[2] * smp[3]; c[3] += smp[3];
            }
            if (c[3] <= 0) continue;
            double cov = c[3] / (ss * ss) * opacity;
            c[0] /= c[3]; c[1] /= c[3]; c[2] /= c[3];
            uint8_t *d = dst->rgb + ((size_t)py * dst->w + px) * 3;
            for (int k = 0; k < 3; k++) d[k] = clamp8(d[k] + (c[k] - d[k]) * cov);
        }
    }
}

/* ---- BGRT ------------------------------------------------------------------------- */
static inline uint32_t rd32(const uint8_t *p) { return p[0] | p[1] << 8 | p[2] << 16 | (uint32_t)p[3] << 24; }
static inline uint16_t rd16(const uint8_t *p) { return p[0] | p[1] << 8; }

/* decode a BMP (24/32 bpp BI_RGB, 8 bpp palette; bottom-up or top-down) into RGB888 */
static int decode_bmp(const uint8_t *d, size_t n, Img *out) {
    if (n < 54 || d[0] != 'B' || d[1] != 'M') return -1;
    uint32_t off = rd32(d + 10), dib = rd32(d + 14);
    int32_t w = (int32_t)rd32(d + 18), h = (int32_t)rd32(d + 22);
    int bpp = rd16(d + 28); uint32_t comp = rd32(d + 30);
    int topdown = h < 0; if (topdown) h = -h;
    if (w <= 0 || h <= 0 || w > 8192 || h > 8192) return -1;
    if (!(bpp == 24 || bpp == 32 || bpp == 8) || (comp != 0 && comp != 3)) return -1;
    size_t rowbytes = (((size_t)w * bpp + 31) / 32) * 4;
    if (off + rowbytes * (size_t)h > n) return -1;
    const uint8_t *pal = d + 14 + dib; int ncol = bpp == 8 ? (int)rd32(d + 46) : 0;
    if (bpp == 8 && ncol == 0) ncol = 256;
    if (bpp == 8 && (size_t)(pal - d) + (size_t)ncol * 4 > n) return -1;
    out->w = w; out->h = h; out->rgb = malloc((size_t)w * h * 3);
    if (!out->rgb) return -1;
    for (int y = 0; y < h; y++) {
        const uint8_t *row = d + off + rowbytes * (size_t)(topdown ? y : h - 1 - y);
        uint8_t *o = out->rgb + (size_t)y * w * 3;
        for (int x = 0; x < w; x++, o += 3) {
            if (bpp == 24) { o[0] = row[x * 3 + 2]; o[1] = row[x * 3 + 1]; o[2] = row[x * 3]; }
            else if (bpp == 32) { o[0] = row[x * 4 + 2]; o[1] = row[x * 4 + 1]; o[2] = row[x * 4]; }
            else { int c = row[x]; if (c >= ncol) c = 0; o[0] = pal[c * 4 + 2]; o[1] = pal[c * 4 + 1]; o[2] = pal[c * 4]; }
        }
    }
    return 0;
}

static int read_int_at(int dfd, const char *path, int dflt) {
    char b[64]; if (read_file_at(dfd, path, b, sizeof b) <= 0) return dflt;
    return (int)strtol(b, NULL, 0);
}

static void load_bgrt(Bgrt *bg, const char *dir) {
    memset(bg, 0, sizeof *bg);
    int dfd = open(dir, O_RDONLY | O_DIRECTORY | O_CLOEXEC);
    if (dfd < 0) { logmsg("bgrt: no %s (%s) — no firmware logo", dir, strerror(errno)); return; }
    int fd = openat(dfd, "image", O_RDONLY | O_CLOEXEC);
    if (fd < 0) { logmsg("bgrt: no image in %s — no firmware logo", dir); close(dfd); return; }
    size_t cap = 1 << 20, n = 0; uint8_t *buf = malloc(cap);
    for (;;) {
        if (!buf) break;
        if (n == cap) { cap *= 2; if (cap > 64u << 20) break; uint8_t *nb = realloc(buf, cap); if (!nb) break; buf = nb; }
        ssize_t r = read(fd, buf + n, cap - n);
        if (r <= 0) break;
        n += r;
    }
    close(fd);
    bg->status = read_int_at(dfd, "status", 0); bg->type = read_int_at(dfd, "type", 0);
    bg->version = read_int_at(dfd, "version", 0);
    bg->xoff = read_int_at(dfd, "xoffset", 0); bg->yoff = read_int_at(dfd, "yoffset", 0);
    close(dfd);
    if (!buf || decode_bmp(buf, n, &bg->img) != 0) {
        logmsg("bgrt: image unreadable (%zu bytes) — no firmware logo", n);
        free(buf); return;
    }
    free(buf);
    /* non-black bounding box */
    int x0 = bg->img.w, y0 = bg->img.h, x1 = -1, y1 = -1;
    for (int y = 0; y < bg->img.h; y++) {
        const uint8_t *p = bg->img.rgb + (size_t)y * bg->img.w * 3;
        for (int x = 0; x < bg->img.w; x++, p += 3) {
            int m = p[0] > p[1] ? p[0] : p[1]; if (p[2] > m) m = p[2];
            if (m > BBOX_THRESHOLD) { if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y; }
        }
    }
    if (x1 < 0) { x0 = 0; y0 = 0; x1 = bg->img.w - 1; y1 = bg->img.h - 1; }   /* all black: treat the whole image as the logo */
    bg->bx0 = x0; bg->by0 = y0; bg->bx1 = x1 + 1; bg->by1 = y1 + 1;
    bg->present = 1;
    logmsg("bgrt: %dx%d bmp at +%d+%d (status %d type %d v%d), logo bbox %d,%d-%d,%d",
           bg->img.w, bg->img.h, bg->xoff, bg->yoff, bg->status, bg->type, bg->version, x0, y0, x1 + 1, y1 + 1);
}

/* scaled copy of an RGB image (area-average when shrinking, bilinear when growing) */
static void blit_img(Img *dst, const Img *src, int dx, int dy, int dw, int dh) {
    if (dw <= 0 || dh <= 0) return;
    double sx = (double)src->w / dw, sy = (double)src->h / dh;
    for (int y = 0; y < dh; y++) {
        int py = dy + y; if (py < 0 || py >= dst->h) continue;
        double v0 = y * sy, v1 = (y + 1) * sy;
        for (int x = 0; x < dw; x++) {
            int px = dx + x; if (px < 0 || px >= dst->w) continue;
            double u0 = x * sx, u1 = (x + 1) * sx;
            double acc[3] = {0, 0, 0}, wsum = 0;
            int ys = (int)floor(v0), ye = (int)ceil(v1), xs = (int)floor(u0), xe = (int)ceil(u1);
            if (ye - ys > 6) ye = ys + 6;
            if (xe - xs > 6) xe = xs + 6;
            for (int j = ys; j < ye; j++) for (int i = xs; i < xe; i++) {
                if (i < 0 || j < 0 || i >= src->w || j >= src->h) continue;
                double wx = fmin(u1, i + 1) - fmax(u0, i), wy = fmin(v1, j + 1) - fmax(v0, j);
                if (wx <= 0 || wy <= 0) continue;
                const uint8_t *p = src->rgb + ((size_t)j * src->w + i) * 3;
                acc[0] += p[0] * wx * wy; acc[1] += p[1] * wx * wy; acc[2] += p[2] * wx * wy; wsum += wx * wy;
            }
            if (wsum <= 0) continue;
            uint8_t *d = dst->rgb + ((size_t)py * dst->w + px) * 3;
            d[0] = clamp8(acc[0] / wsum); d[1] = clamp8(acc[1] / wsum); d[2] = clamp8(acc[2] / wsum);
        }
    }
}

/* ---- layout ----------------------------------------------------------------------- */
typedef struct {
    double scale;                 /* ref -> screen scale for the firmware logo (1.0 when the mode is the GOP mode) */
    int bgrt_x, bgrt_y, bgrt_w, bgrt_h;   /* where the BGRT lands on screen */
    int logo1_x, logo1_y, logo1_w, logo1_h;
    double s2;                    /* phase-2 scale: min(W/1920, H/1080) */
    int logo2_x, logo2_y, logo2_w, logo2_h;
    double bar_x, bar_y, bar_w, bar_h, bar_r;   /* track (centre y), reference-scaled */
    int reg_x0, reg_y0, reg_x1, reg_y1;         /* dirty region of the bar incl. glow */
} Layout;

/* ref_w/ref_h: the GOP mode the BGRT offsets refer to (the first fb seen), W/H: the current fb */
static Layout layout_for(int W, int H, int ref_w, int ref_h, const Bgrt *bg, const Sprite *l1, const Sprite *l2) {
    Layout L; memset(&L, 0, sizeof L);
    double sw = (double)W / ref_w, sh = (double)H / ref_h;
    L.scale = fmin(sw, sh);
    double ox = (W - ref_w * L.scale) / 2, oy = (H - ref_h * L.scale) / 2;
    double k = fmin(W / REF_W, H / REF_H);          /* lockup size follows the screen */
    L.logo1_w = (int)lround(l1->w * k); L.logo1_h = (int)lround(l1->h * k);
    if (L.logo1_w < 1) L.logo1_w = 1;
    if (L.logo1_h < 1) L.logo1_h = 1;
    if (bg->present) {
        double bx = ox + bg->xoff * L.scale, by = oy + bg->yoff * L.scale;
        L.bgrt_x = (int)lround(bx); L.bgrt_y = (int)lround(by);
        L.bgrt_w = (int)lround(bg->img.w * L.scale); L.bgrt_h = (int)lround(bg->img.h * L.scale);
        if (L.bgrt_w < 1) L.bgrt_w = 1;
        if (L.bgrt_h < 1) L.bgrt_h = 1;
        double bbcx = bx + (bg->bx0 + bg->bx1) / 2.0 * L.scale;
        double bbbot = by + bg->by1 * L.scale;
        L.logo1_x = (int)lround(bbcx - L.logo1_w / 2.0);
        L.logo1_y = (int)lround(bbbot + LAYOUT_LOGO1_GAP * H);
        int ymax = (int)(H - 0.03 * H) - L.logo1_h;
        if (L.logo1_y > ymax) L.logo1_y = ymax;
        if (L.logo1_y < 0) L.logo1_y = 0;
        if (L.logo1_x < 0) L.logo1_x = 0;
        if (L.logo1_x + L.logo1_w > W) L.logo1_x = W - L.logo1_w;
    } else {
        L.logo1_x = (int)lround(W / 2.0 - L.logo1_w / 2.0);
        L.logo1_y = (int)lround(LAYOUT_LOGO1_CY * H - L.logo1_h / 2.0);
    }
    L.s2 = k;
    L.logo2_w = (int)lround(l2->w * k); L.logo2_h = (int)lround(l2->h * k);
    if (L.logo2_w < 1) L.logo2_w = 1;
    if (L.logo2_h < 1) L.logo2_h = 1;
    L.logo2_x = (int)lround(W / 2.0 - L.logo2_w / 2.0);
    L.logo2_y = (int)lround(LAYOUT_LOGO2_CY * H - L.logo2_h / 2.0);
    L.bar_w = LAYOUT_BAR_W * k; L.bar_h = fmax(4.0, LAYOUT_BAR_H * k); L.bar_r = L.bar_h / 2;
    L.bar_x = W / 2.0 - L.bar_w / 2; L.bar_y = LAYOUT_BAR_CY * H;
    double m = LAYOUT_BAR_GLOW * k + 2;
    L.reg_x0 = (int)floor(L.bar_x - m); L.reg_x1 = (int)ceil(L.bar_x + L.bar_w + m);
    L.reg_y0 = (int)floor(L.bar_y - L.bar_h / 2 - m); L.reg_y1 = (int)ceil(L.bar_y + L.bar_h / 2 + m);
    if (L.reg_x0 < 0) L.reg_x0 = 0;
    if (L.reg_y0 < 0) L.reg_y0 = 0;
    if (L.reg_x1 > W) L.reg_x1 = W;
    if (L.reg_y1 > H) L.reg_y1 = H;
    return L;
}

/* ---- progress model --------------------------------------------------------------- */
typedef struct {
    double expected;
    double floor;          /* highest milestone floor seen */
    double shown;          /* eased, monotonic value on screen */
    double target;
    int have_root, have_userspace, have_x;
} Progress;

static double progress_curve(double t, double expected) {
    if (expected < 1) expected = 1;
    double u = t / expected;
    if (u <= 1.0) return P_AT_EXPECTED * u;
    return P_AT_EXPECTED + (P_MAX - P_AT_EXPECTED) * (1 - exp(-(u - 1) * 2.0));
}

static double progress_target(const Progress *p, double t) {
    double v = progress_curve(t, p->expected);
    if (v < p->floor) v = p->floor;
    if (v > P_MAX) v = P_MAX;
    return v;
}

/* ---- rendering -------------------------------------------------------------------- */
static void render_background(Img *bg) {
    int W = bg->w, H = bg->h;
    /* CSS linear-gradient(160deg, top 0%, mid 50%, bot 100%) */
    double a = 160.0 * M_PI / 180.0, dx = sin(a), dy = -cos(a);
    double len = fabs(W * dx) + fabs(H * dy);
    double cx = W / 2.0, cy = H / 2.0;
    /* radial glows: (centre fraction, radii in reference px, fade end) */
    double g1cx = 0.75 * W, g1cy = 0.15 * H, g1rx = 1200.0 / REF_W * W, g1ry = 700.0 / REF_H * H;
    double g2cx = 0.15 * W, g2cy = 0.85 * H, g2rx = 900.0 / REF_W * W, g2ry = 600.0 / REF_H * H;
    for (int y = 0; y < H; y++) {
        uint8_t *o = bg->rgb + (size_t)y * W * 3;
        for (int x = 0; x < W; x++, o += 3) {
            double t = ((x + 0.5 - cx) * dx + (y + 0.5 - cy) * dy) / len + 0.5;
            t = clampd(t, 0, 1);
            uint8_t c[3];
            if (t < 0.5) lerp3(c, BG_TOP, BG_MID, t * 2); else lerp3(c, BG_MID, BG_BOT, (t - 0.5) * 2);
            double d2 = hypot((x - g2cx) / g2rx, (y - g2cy) / g2ry);
            if (d2 < 0.55) lerp3(c, c, GLOW2, 1 - d2 / 0.55);
            double d1 = hypot((x - g1cx) / g1rx, (y - g1cy) / g1ry);
            if (d1 < 0.60) lerp3(c, c, GLOW1, 1 - d1 / 0.60);
            o[0] = c[0]; o[1] = c[1]; o[2] = c[2];
        }
    }
}

static inline double sd_round_rect(double x, double y, double cx, double cy, double hw, double hh, double r) {
    double qx = fabs(x - cx) - (hw - r), qy = fabs(y - cy) - (hh - r);
    double ax = qx > 0 ? qx : 0, ay = qy > 0 ? qy : 0;
    double outside = hypot(ax, ay);
    double inside = fmin(fmax(qx, qy), 0.0);
    return outside + inside - r;
}

/* the bar (track, fill, glow, moving highlight) into dst's bar region, over the background */
static void render_bar(Img *dst, const Img *bg, const Layout *L, double p, double t) {
    double cy = L->bar_y, hh = L->bar_h / 2, r = L->bar_r;
    double tcx = L->bar_x + L->bar_w / 2, thw = L->bar_w / 2;
    double fill_w = fmax(p * L->bar_w, 2 * r), fcx = L->bar_x + fill_w / 2, fhw = fill_w / 2;
    double glow_len = 6.0 * L->s2 + 1.5;
    double band = 0.16 * L->bar_w;
    double hx = L->bar_x - band + fmod(t, HIGHLIGHT_PERIOD_S) / HIGHLIGHT_PERIOD_S * (fill_w + 2 * band);
    for (int y = L->reg_y0; y < L->reg_y1; y++) {
        const uint8_t *s = bg->rgb + ((size_t)y * bg->w + L->reg_x0) * 3;
        uint8_t *o = dst->rgb + ((size_t)y * dst->w + L->reg_x0) * 3;
        for (int x = L->reg_x0; x < L->reg_x1; x++, s += 3, o += 3) {
            double px = x + 0.5, py = y + 0.5;
            double c[3] = {s[0], s[1], s[2]};
            double dt = sd_round_rect(px, py, tcx, cy, thw, hh, r);
            double df = sd_round_rect(px, py, fcx, cy, fhw, hh, r);
            double u = clampd((px - L->bar_x) / L->bar_w, 0, 1);
            double fc[3] = {ACCENT[0] + (ACCENT2[0] - ACCENT[0]) * u, ACCENT[1] + (ACCENT2[1] - ACCENT[1]) * u,
                            ACCENT[2] + (ACCENT2[2] - ACCENT[2]) * u};
            /* track: 9 % white */
            double ct = clampd(0.5 - dt, 0, 1);
            if (ct > 0) for (int k = 0; k < 3; k++) c[k] += (255 - c[k]) * 0.09 * ct;
            /* glow around the fill */
            if (df > 0) {
                double g = 0.5 * exp(-df / glow_len);
                for (int k = 0; k < 3; k++) c[k] += (fc[k] - c[k]) * g;
            }
            /* fill with the moving highlight */
            double cf = clampd(0.5 - df, 0, 1);
            if (cf > 0) {
                double hl = 0.38 * exp(-pow((px - hx) / (band * 0.5), 2));
                double fh[3] = {fc[0] + (255 - fc[0]) * hl, fc[1] + (255 - fc[1]) * hl, fc[2] + (255 - fc[2]) * hl};
                for (int k = 0; k < 3; k++) c[k] += (fh[k] - c[k]) * cf;
            }
            o[0] = clamp8(c[0]); o[1] = clamp8(c[1]); o[2] = clamp8(c[2]);
        }
    }
}

static void render_phase1(Img *dst, const Layout *L, const Bgrt *bg, const Sprite *l1) {
    memset(dst->rgb, 0, (size_t)dst->w * dst->h * 3);
    if (bg->present) blit_img(dst, &bg->img, L->bgrt_x, L->bgrt_y, L->bgrt_w, L->bgrt_h);
    blit_sprite(dst, l1, L->logo1_x, L->logo1_y, L->logo1_w, L->logo1_h, 1.0);
}

static void render_phase2_base(Img *dst, const Img *bg, const Layout *L, const Sprite *l2) {
    memcpy(dst->rgb, bg->rgb, (size_t)dst->w * dst->h * 3);
    blit_sprite(dst, l2, L->logo2_x, L->logo2_y, L->logo2_w, L->logo2_h, 1.0);
}

/* ---- framebuffer layer -------------------------------------------------------------- */
static int fb_read_sys(const char *name, char *buf, size_t cap) {
    /* file mode: KAIROS_FB_SYS is a plain directory path; device mode: via the sysfs dirfd */
    if (opt.fb_path && sysfd < 0) {
        char p[512]; snprintf(p, sizeof p, "%s/%s", opt.fb_sys, name);
        return read_file_at(-1, p, buf, cap);
    }
    char p[64]; snprintf(p, sizeof p, "%s", name);
    return read_file_at(sysfd, p, buf, cap);
}

static void fb_close(Fb *fb) { if (fb->fd >= 0) close(fb->fd); fb->fd = -1; }

/* FBIOGET_VSCREENINFO before every frame: 0 ok, -1 ENODEV (handover), -2 other error */
static int fb_query(Fb *fb) {
    if (fb->file_mode) {
        char b[256];
        char p[512]; snprintf(p, sizeof p, "%s/enodev", opt.fb_sys);
        if (access(p, F_OK) == 0) { errno = ENODEV; return -1; }
        if (fb_read_sys("virtual_size", b, sizeof b) <= 0) return -2;
        int w = 0, h = 0; if (sscanf(b, "%d,%d", &w, &h) != 2 || w <= 0 || h <= 0) return -2;
        int bpp = 32, stride = 0;
        if (fb_read_sys("bits_per_pixel", b, sizeof b) > 0) bpp = atoi(b);
        if (fb_read_sys("stride", b, sizeof b) > 0) stride = atoi(b);
        if (stride <= 0) stride = w * bpp / 8;
        fb->w = w; fb->h = h; fb->bpp = bpp; fb->stride = stride;
        if (bpp == 16) { fb->ro = 11; fb->rl = 5; fb->go = 5; fb->gl = 6; fb->bo = 0; fb->bl = 5; }
        else { fb->ro = 16; fb->rl = 8; fb->go = 8; fb->gl = 8; fb->bo = 0; fb->bl = 8; }
        if (fb_read_sys("name", b, sizeof b) > 0) { b[strcspn(b, "\n")] = 0; snprintf(fb->name, sizeof fb->name, "%.31s", b); }
        return 0;
    }
    struct fb_var_screeninfo v;
    if (ioctl(fb->fd, FBIOGET_VSCREENINFO, &v) != 0) return errno == ENODEV ? -1 : -2;
    struct fb_fix_screeninfo f;
    if (ioctl(fb->fd, FBIOGET_FSCREENINFO, &f) != 0) return errno == ENODEV ? -1 : -2;
    fb->w = v.xres; fb->h = v.yres; fb->bpp = v.bits_per_pixel; fb->stride = f.line_length;
    fb->ro = v.red.offset; fb->rl = v.red.length; fb->go = v.green.offset; fb->gl = v.green.length;
    fb->bo = v.blue.offset; fb->bl = v.blue.length;
    snprintf(fb->name, sizeof fb->name, "%.15s", f.id);
    if (fb->w <= 0 || fb->h <= 0 || fb->stride <= 0 || !(fb->bpp == 32 || fb->bpp == 24 || fb->bpp == 16)) return -2;
    return 0;
}

static int fb_open(Fb *fb) {
    fb_close(fb);
    if (opt.fb_path) {
        struct stat st;
        if (stat(opt.fb_path, &st) == 0 && S_ISREG(st.st_mode)) fb->file_mode = 1;
        else if (stat(opt.fb_path, &st) != 0 && opt.fb_sys && strncmp(opt.fb_path, "/dev/", 5) != 0) fb->file_mode = 1;
        fb->fd = open(opt.fb_path, O_RDWR | O_CLOEXEC | (fb->file_mode ? O_CREAT : 0), 0644);
    } else {
        fb->fd = openat(devfd, "fb0", O_RDWR | O_CLOEXEC);
    }
    if (fb->fd < 0) return -1;
    int r = fb_query(fb);
    if (r != 0) { fb_close(fb); return r == -1 ? -1 : -2; }
    fb->generation++;
    return 0;
}

/* convert one RGB888 row segment to the fb's pixel format */
static void convert_row(const Fb *fb, const uint8_t *rgb, int npx, uint8_t *out) {
    int bypp = fb->bpp / 8;
    if (fb->bpp == 32 || fb->bpp == 24) {
        int ri = fb->ro / 8, gi = fb->go / 8, bi = fb->bo / 8;
        if (ri > bypp - 1 || gi > bypp - 1 || bi > bypp - 1) { ri = 2; gi = 1; bi = 0; }
        for (int x = 0; x < npx; x++, rgb += 3, out += bypp) {
            if (bypp == 4) out[3] = 0;
            out[ri] = rgb[0]; out[gi] = rgb[1]; out[bi] = rgb[2];
        }
    } else {   /* 16 bpp, generic bitfields */
        for (int x = 0; x < npx; x++, rgb += 3, out += 2) {
            uint32_t v = ((rgb[0] >> (8 - fb->rl)) << fb->ro) | ((rgb[1] >> (8 - fb->gl)) << fb->go) | ((rgb[2] >> (8 - fb->bl)) << fb->bo);
            out[0] = v & 0xff; out[1] = (v >> 8) & 0xff;
        }
    }
}

/* write rows y0..y1 (exclusive), columns x0..x1 of img to the fb; 0 ok, -1 ENODEV, -2 other */
static int fb_write_region(Fb *fb, const Img *img, int x0, int y0, int x1, int y1) {
    if (fb->fd < 0) return -2;
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 > fb->w) x1 = fb->w;
    if (y1 > fb->h) y1 = fb->h;
    if (x1 > img->w) x1 = img->w;
    if (y1 > img->h) y1 = img->h;
    if (x1 <= x0 || y1 <= y0) return 0;
    int bypp = fb->bpp / 8, npx = x1 - x0;
    static uint8_t *rowbuf = NULL; static size_t rowcap = 0;
    size_t need = (size_t)npx * bypp;
    if (need > rowcap) { free(rowbuf); rowbuf = malloc(need); rowcap = need; if (!rowbuf) { rowcap = 0; return -2; } }
    for (int y = y0; y < y1; y++) {
        convert_row(fb, img->rgb + ((size_t)y * img->w + x0) * 3, npx, rowbuf);
        off_t off = (off_t)y * fb->stride + (off_t)x0 * bypp;
        size_t done = 0;
        while (done < need) {
            ssize_t r = pwrite(fb->fd, rowbuf + done, need - done, off + done);
            if (r < 0) { if (errno == EINTR) continue; return errno == ENODEV ? -1 : -2; }
            if (r == 0) return -2;
            done += r;
        }
    }
    return 0;
}

/* ---- VT mode ---------------------------------------------------------------------- */
static void vt_open(void) {
    if (!opt.tty_path || !*opt.tty_path || !strcmp(opt.tty_path, "none")) return;
    ttyfd = open(opt.tty_path, O_RDWR | O_NOCTTY | O_CLOEXEC);
    if (ttyfd < 0) logmsg("vt: cannot open %s (%s) — fbcon stays in charge of the console", opt.tty_path, strerror(errno));
}

static int vt_get_mode(void) {
    long m = -1;
    if (ttyfd < 0 || ioctl(ttyfd, KDGETMODE, &m) != 0) return -1;
    return (int)m;
}

static int vt_set_mode(long mode) {
    if (ttyfd < 0) return -1;
    return ioctl(ttyfd, KDSETMODE, mode);
}

/* ---- signals ---------------------------------------------------------------------- */
static void on_term(int s) { (void)s; sig_term = s; }
static void on_usr1(int s) { (void)s; sig_usr1 = 1; }
static void on_crash(int s) {
    /* async-signal-safe only: the console back, a trace line, then the default action */
    if (ttyfd >= 0 && kd_graphics_set) ioctl(ttyfd, KDSETMODE, KD_TEXT);
    static const char m[] = "splash: CRASH (signal) — text console restored\n";
    if (logfd >= 0) { ssize_t r = write(logfd, m, sizeof m - 1); (void)r; }
    signal(s, SIG_DFL);
    raise(s);
}

/* ---- control files ---------------------------------------------------------------- */
static int ctl_exists(const char *rel) { return faccessat(runfd, rel, F_OK, 0) == 0; }

static int read_pidfile(void) {
    char b[32]; if (read_file_at(runfd, "kairos-splash.pid", b, sizeof b) <= 0) return -1;
    int pid = atoi(b); return pid > 1 ? pid : -1;
}

/* append the run log to the archive (through PID 1's root, which is the real root after switch_root) */
static void archive_log(void) {
    if (logfd < 0) return;
    char src[512], dst[512];
    int fd = -1;
    if (opt.log_path[0] == '/' && strncmp(opt.log_path, "/run/", 5) == 0) {
        snprintf(src, sizeof src, "%s", opt.log_path + 5);
        fd = openat(runfd, src, O_RDONLY | O_CLOEXEC);
    } else fd = open(opt.log_path, O_RDONLY | O_CLOEXEC);
    if (fd < 0) return;
    snprintf(dst, sizeof dst, "1/root%s", opt.archive_path);
    int out = procfd >= 0 ? openat(procfd, dst, O_WRONLY | O_APPEND | O_CREAT | O_CLOEXEC, 0644) : -1;
    if (out < 0) out = open(opt.archive_path, O_WRONLY | O_APPEND | O_CREAT | O_CLOEXEC, 0644);
    if (out < 0) { close(fd); return; }
    char buf[4096]; ssize_t n;
    while ((n = read(fd, buf, sizeof buf)) > 0) { ssize_t r = write(out, buf, n); (void)r; }
    close(fd); close(out);
}

static void leave(const char *why, int restore_text) {
    struct rusage ru;
    if (getrusage(RUSAGE_SELF, &ru) == 0)
        logmsg("cpu used: %.2fs user + %.2fs sys over %.1fs", ru.ru_utime.tv_sec + ru.ru_utime.tv_usec / 1e6,
               ru.ru_stime.tv_sec + ru.ru_stime.tv_usec / 1e6, now_boot() - t_start);
    if (restore_text && kd_graphics_set) {
        if (vt_set_mode(KD_TEXT) == 0) logmsg("%s — text console restored (KD_TEXT)", why);
        else logmsg("%s — KD_TEXT failed: %s", why, strerror(errno));
    } else {
        logmsg("%s — VT mode untouched", why);
    }
    unlinkat(runfd, "kairos-splash.pid", 0);
    archive_log();
    _exit(0);
}

/* ---- --stop / --text helpers (run from the panic hook, the emergency drop-ins, tests) ---- */
static int cmd_text(void) {
    vt_open();
    if (ttyfd < 0) return 1;
    int r = vt_set_mode(KD_TEXT);
    if (r != 0) fprintf(stderr, "kairos-splash: KD_TEXT on %s failed: %s\n", opt.tty_path, strerror(errno));
    return r == 0 ? 0 : 1;
}

static int cmd_stop(void) {
    int pid = read_pidfile();
    if (pid > 1 && kill(pid, SIGTERM) == 0) {
        for (int i = 0; i < 150; i++) {        /* up to 1.5 s for the painter's own KD_TEXT + log */
            if (kill(pid, 0) != 0 && errno == ESRCH) break;
            usleep(10000);
        }
    }
    return cmd_text();   /* belt and braces: the console comes back even if the painter was gone */
}

